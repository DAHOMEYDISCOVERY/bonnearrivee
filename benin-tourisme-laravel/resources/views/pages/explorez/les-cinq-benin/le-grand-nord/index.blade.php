<div class="woody-component woody-component-custom-text tpl_02 flex-container flex-dir-column align-center no-sessions" data-equalizer="data-equalizer"><header class="section-header-wrapper grid-container grid-default container-min"><div class="section-header text-center"><div class="section-titles flex-container flex-dir-column align-middle align-center text-center"><div class="section-texts has-title has-subtitle"><h2 class="section-title">La chaîne de l'Atacora</h2><span class="section-subtitle block-span">le toit du Bénin</span></div></div></div></header><div class="grid-container"><div class="grid-x grid-padding-x"><div class="cell"><p>La <strong>chaîne de l'Atacora</strong> court sur près de <strong>quatre cents kilomètres</strong> au nord-ouest du pays, du Togo au Burkina Faso. Ses crêtes gréseuses culminent au <strong>mont Sokbaro</strong>, à 658 mètres — plus haut sommet du Bénin.</p><p>Elle abrite les <strong>chutes de Tanougou</strong>, la <strong>Pendjari</strong> et sa faune, les <strong>tata somba</strong> des Betammaribé, et une mosaïque de villages qui vivent au rythme des cultures pluviales : mil, sorgho, igname, arachide. C'est la région du Bénin la plus verte en saison des pluies, la plus rude en saison sèche.</p></div></div></div></div>
<div class="woody-component woody-component-custom-text tpl_02 bg-primary bg-gradient bg-filigrane isRel padd-all-md no-sessions" data-equalizer="data-equalizer"><div class="grid-container"><div class="grid-x grid-padding-x align-center"><div class="cell large-8 text-center"><h2 class="section-title">L'anacarde du Nord</h2><p>Le Bénin est le <strong>quatrième producteur africain d'anacarde</strong>, avec près de <strong>180 000 tonnes par an</strong>. La ceinture de production court de <strong>Bembèrèkè</strong> à <strong>Nikki</strong> en passant par <strong>Parakou</strong>. En avril, les vergers se couvrent de pommes rouges et jaunes ; sous chacune, la noix — celle qu'on rôtit, décortique, puis exporte vers l'Inde et le Vietnam.</p><p>La transformation commence à s'installer : coopératives à Tchaourou, Sinendé, Kalalé. Une visite dans une petite unité artisanale apprend en une heure ce qui distingue une noix de qualité, comment se casse une coque sans blesser l'amande, et pourquoi la couleur d'une pomme se lit comme sa saison.</p></div></div></div></div>
<div class="woody-component woody-component-custom-text tpl_02 bg-primary bg-gradient bg-filigrane isRel padd-all-md no-sessions" data-equalizer="data-equalizer"><div class="grid-container"><div class="grid-x grid-padding-x align-center"><div class="cell large-8 text-center"><h2 class="section-title">Les cascades pour se ressourcer</h2><p>Le Nord béninois est le pays des chutes d'eau. Les <strong>chutes de Tanougou</strong>, à quinze kilomètres de Tanguiéta, dévalent le grès de l'Atacora sur trente mètres et forment un bassin où l'on peut se baigner presque toute l'année. Les <strong>chutes de Kota</strong>, plus discrètes, se méritent après une marche d'une heure depuis Natitingou. Plus au sud, la <strong>Kaboua</strong> et le <strong>saut du Roc</strong>, près de Savalou, achèvent le circuit.</p><p>Toutes se visitent avec un guide local : la végétation cache les sentiers pendant la saison des pluies, et la profondeur des vasques change d'une année à l'autre.</p></div></div></div></div>
<div class="page-section page-section-3" id="pageSection-3"><section class="section bg-motif padd-top-md padd-bottom-md marg-top-none marg-bottom-none"><header class="section-header-wrapper grid-container grid-default container-min"><div class="section-header text-center"><div class="section-titles flex-container flex-dir-column align-middle align-center text-center"><div class="section-texts has-title has-subtitle"><h2 class="section-title">Les tata somba</h2><span class="section-subtitle block-span">forteresses de terre du pays Betammaribé</span></div></div></div></header><article class="section-layout-wrapper grid-container grid-default"><div class="woody-component woody-component-custom-text tpl_02"><div class="grid-x grid-padding-x align-center"><div class="cell large-10"><p>Autour de <strong>Boukombé</strong>, les <strong>tata somba</strong> se dressent seules dans la savane. Ces maisons-tours en banco, deux étages sous une terrasse de terre battue, sont l'œuvre des <strong>Betammaribé</strong>. Chaque tata abrite une famille — hommes et bétail au rez-de-chaussée, greniers et couchages à l'étage, autel des ancêtres à l'entrée.</p><p>L'architecture parle d'histoire : ce sont d'anciennes fortifications, adoptées quand les razzias esclavagistes du <strong>XVIIIᵉ siècle</strong> menaçaient la région. Elles se visitent avec un habitant, qui explique la répartition des pièces, la fabrication du banco et les rituels d'inauguration — chaque tata neuve est un événement dans le village. Le pays Betammaribé est <strong>inscrit au patrimoine mondial de l'UNESCO côté togolais</strong> depuis 2004 ; l'inscription du côté béninois est portée par les autorités.</p></div></div></div></article></section></div>
